"""Backlog for framework/code improvements (owned by the framework-engineer agent).

    python -m lfd.backlog save-meeting --title "prof sync replay budget" --file <pasted.txt>
        -> research/meetings/<ts>__meeting__<title>.md   (verbatim, never edited afterwards)
    python -m lfd.backlog new --title "..." --type feature --scope opt-in-feature --priority P2 \
        --source research/meetings/<file>.md --body-file <tmp.md>
        -> research/backlog/items/BL-0007__<title>.md
    python -m lfd.backlog set BL-0007 status=in-progress branch=bl-0007-replay-budget
    python -m lfd.backlog list [--status new]
    python -m lfd.backlog render        -> research/BACKLOG.md (board grouped by status; regenerate after every change)

Fields
  status   new | needs-clarification | accepted | in-progress | done | wont-do | blocked
  type     bug | feature | improvement | refactor | research-idea | chore
  scope    core-pyclad      generic, additive -> src/pyclad (+ tests/), upstream-PR candidate
           core-lfd         generic harness tooling -> lfd/ (naming, evaluation, logging ...)
           opt-in-feature   changes training/eval behaviour or is specific -> lfd/features/<name>.py, off by default
           experiment       not code: hand over as an improvement proposal (evaluator/experiment-runner)
           data             not code: hand over to data-processor as a data proposal
  priority P1 | P2 | P3
"""
from __future__ import annotations

import argparse
import datetime as _dt
import os
import re
from pathlib import Path

from lfd import naming
from lfd.proposals import _read, _write

BACKLOG = naming.RESEARCH / "backlog"
ITEMS = BACKLOG / "items"
MEETINGS = naming.RESEARCH / "meetings"
STATUSES = ["in-progress", "accepted", "new", "needs-clarification", "blocked", "done", "wont-do"]
TYPES = ["bug", "feature", "improvement", "refactor", "research-idea", "chore"]
SCOPES = ["core-pyclad", "core-lfd", "opt-in-feature", "experiment", "data"]


def _now() -> str:
    return _dt.datetime.now().isoformat(timespec="seconds")


def _items() -> list[tuple[Path, dict]]:
    return [(p, _read(p)[0]) for p in sorted(ITEMS.glob("BL-*.md"))]


def _next_id() -> str:
    nums = [int(m.group(1)) for p, _ in _items() if (m := re.match(r"BL-(\d+)", p.name))]
    return f"BL-{(max(nums) + 1) if nums else 1:04d}"


def find(item_id: str) -> Path:
    hits = list(ITEMS.glob(f"{item_id}__*.md"))
    if len(hits) != 1:
        raise SystemExit(f"backlog item {item_id} not found")
    return hits[0]


def save_meeting(title: str, src: Path) -> Path:
    MEETINGS.mkdir(parents=True, exist_ok=True)
    dst = MEETINGS / f"{naming.timestamp()}__meeting__{naming.slug(title, 60)}.md"
    i = 1
    while dst.exists():
        i += 1
        dst = dst.with_name(dst.stem + f"__r{i}.md")
    text = Path(src).read_text(encoding="utf-8")
    dst.write_text(f"<!-- saved {_now()} - verbatim, do not edit -->\n# {title}\n\n{text}", encoding="utf-8")
    return dst


def new(title, type_, scope, priority, source, body) -> Path:
    for v, allowed, name in ((type_, TYPES, "type"), (scope, SCOPES, "scope"), (priority, ["P1", "P2", "P3"], "priority")):
        if v not in allowed:
            raise SystemExit(f"{name} must be one of {allowed}")
    ITEMS.mkdir(parents=True, exist_ok=True)
    iid = _next_id()
    path = ITEMS / f"{iid}__{naming.slug(title, 60)}.md"
    _write(path, {"id": iid, "title": title, "status": "new", "type": type_, "scope": scope,
                  "priority": priority, "source": source or "", "created": _now(), "updated": _now(),
                  "branch": "", "commits": "", "feature_flag": "", "changelog": ""},
           body if body.endswith("\n") else body + "\n")
    return path


def set_fields(item_id: str, pairs: list[str]) -> Path:
    path = find(item_id)
    header, body = _read(path)
    for kv in pairs:
        k, _, v = kv.partition("=")
        if k == "status" and v not in STATUSES:
            raise SystemExit(f"status must be one of {STATUSES}")
        if k in ("id", "created"):
            raise SystemExit(f"{k} is immutable")
        header[k] = v
    header["updated"] = _now()
    _write(path, header, body)
    return path


def render() -> Path:
    rows = _items()
    out = ["# Backlog\n", f"_Generated by `python -m lfd.backlog render` at {_now()} — do not edit by hand._\n"]
    for st in STATUSES:
        group = [(p, h) for p, h in rows if h.get("status") == st]
        if not group:
            continue
        out.append(f"\n## {st} ({len(group)})\n")
        out.append("| id | P | type | scope | title | flag / branch | source |")
        out.append("|---|---|---|---|---|---|---|")
        for p, h in sorted(group, key=lambda x: (x[1].get("priority", "P9"), x[1]["id"])):
            src = h.get("source", "")
            src_link = f"[{Path(src).stem[:15]}]({os.path.relpath(naming.ROOT / src, naming.RESEARCH)})" if src else ""
            flag = h.get("feature_flag") or h.get("branch") or ""
            out.append(f"| [{h['id']}](backlog/items/{p.name}) | {h.get('priority')} | {h.get('type')} | "
                       f"{h.get('scope')} | {h.get('title')} | {flag} | {src_link} |")
    path = naming.RESEARCH / "BACKLOG.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    return path


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("save-meeting")
    m.add_argument("--title", required=True)
    m.add_argument("--file", required=True)
    n = sub.add_parser("new")
    n.add_argument("--title", required=True)
    n.add_argument("--type", required=True)
    n.add_argument("--scope", required=True)
    n.add_argument("--priority", default="P2")
    n.add_argument("--source", default="")
    n.add_argument("--body-file", required=True)
    s = sub.add_parser("set")
    s.add_argument("id")
    s.add_argument("pairs", nargs="+", metavar="key=value")
    ls = sub.add_parser("list")
    ls.add_argument("--status")
    sub.add_parser("render")
    a = ap.parse_args()

    if a.cmd == "save-meeting":
        print(save_meeting(a.title, Path(a.file)))
    elif a.cmd == "new":
        print(new(a.title, a.type, a.scope, a.priority, a.source, Path(a.body_file).read_text(encoding="utf-8")))
        render()
    elif a.cmd == "set":
        print(set_fields(a.id, a.pairs))
        render()
    elif a.cmd == "list":
        for p, h in _items():
            if not a.status or h.get("status") == a.status:
                print(f"{h['id']} [{h.get('status'):19}] {h.get('priority')} {h.get('scope'):15} {h.get('title')}")
    elif a.cmd == "render":
        print(render())


if __name__ == "__main__":
    main()
